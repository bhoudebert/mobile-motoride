// agentRide exports -> JSON roadbooks the app imports (ADR 0005, ADR 0010).
// Reads `<name>.motoride.json` (limits, cameras: docs/roadbook-format.md) in preference to `<name>.gpx`.
// Usage: node scripts/bundle-roadbooks.ts [folder] [name-fragment ...]
// Default folder: ../agentRide/exports. With name fragments, only matching files are bundled.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { parseGpx, slugify } from "../src/core/gpx.ts";
import { parseRoadbookFile } from "../src/core/roadbookFile.ts";
import type { Roadbook } from "../src/core/types.ts";

const [dirArg, ...filters] = process.argv.slice(2);
const dir = resolve(dirArg ?? "../agentRide/exports");
const out = resolve("src/data/bundled");

const FILE = /^(.*)\.(motoride\.json|gpx)$/;
const all = readdirSync(dir).flatMap((f) => {
  const m = FILE.exec(f);
  return m ? [{ file: f, base: m[1]!, rich: m[2] === "motoride.json" }] : [];
});
// One roadbook per ride: the roadbook file when there is one, else the GPX.
const chosen = [...new Set(all.map((f) => f.base))]
  .map((base) => all.find((f) => f.base === base && f.rich) ?? all.find((f) => f.base === base)!)
  .filter((f) => filters.length === 0 || filters.some((x) => f.file.includes(x)))
  .sort((a, b) => a.file.localeCompare(b.file));
if (chosen.length === 0) throw new Error(`No roadbook file matches in ${dir}`);

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const round = (n: number) => Math.round(n * 1e6) / 1e6;
const ids: string[] = [];

for (const { file, base, rich } of chosen) {
  const text = readFileSync(join(dir, file), "utf8");
  const rb: Roadbook = rich ? parseRoadbookFile(text, slugify(base)) : parseGpx(text, slugify(base));
  const compact = {
    ...rb,
    stops: rb.stops.map((s) => ({ ...s, lat: round(s.lat), lon: round(s.lon) })),
    line: rb.line.map(([lat, lon]) => [round(lat), round(lon)]),
    ...(rb.cameras?.length ? { cameras: rb.cameras.map((c) => ({ ...c, lat: round(c.lat), lon: round(c.lon) })) } : {}),
  };
  if (!rb.limits?.length) delete (compact as { limits?: unknown }).limits;
  if (!rb.cameras?.length) delete (compact as { cameras?: unknown }).cameras;
  if (!rb.countries?.length) delete (compact as { countries?: unknown }).countries;
  if (!rb.junctions?.length) delete (compact as { junctions?: unknown }).junctions;
  writeFileSync(join(out, `${rb.id}.json`), JSON.stringify(compact));
  ids.push(rb.id);
  console.log(
    `${rb.id}: ${rb.line.length} points, ${rb.stops.length} stops` +
      (rich ? `, ${rb.limits?.length ?? 0} limit stretches, ${rb.cameras?.length ?? 0} cameras` : " (GPX, no limits)"),
  );
}

const ident = (id: string) => "rb_" + id.replace(/[^a-z0-9]/g, "_");
const index = [
  "// Generated by scripts/bundle-roadbooks.ts. Do not edit.",
  'import type { Roadbook } from "../../core/types.ts";',
  ...ids.map((id) => `import ${ident(id)} from "./${id}.json";`),
  "",
  `export const bundledRoadbooks: Roadbook[] = [${ids.map((id) => `${ident(id)} as unknown as Roadbook`).join(", ")}];`,
  "",
].join("\n");
writeFileSync(join(out, "index.ts"), index);
